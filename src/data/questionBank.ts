// Helper to filter and retrieve questions without duplicates
export function getQuestionsForConfig(
  mode: string,
  role: string,
  difficulty: DifficultyLevel,
  requestedCount: number = 50
): BankQuestion[] {
  let pool = [...QUESTION_BANK];

  if (mode === 'hr') {
    pool = pool.filter((q) => q.category === 'HR' || q.category === 'Behavioral');
  } else if (mode === 'technical') {
    pool = pool.filter((q) =>
      ['Technical', 'Coding', 'SQL', 'Python', 'Data Analytics', 'Power BI', 'AI/ML', 'Generative AI', 'Prompt Engineering'].includes(
        q.category
      )
    );
  } else if (mode === 'project') {
    pool = pool.filter((q) => q.category === 'Project-based questions' || q.category === 'Behavioral' || q.category === 'Technical');
  }

  // Prioritize based on target role
  if (role === 'Data Analyst') {
    pool.sort((a, b) => {
      const aScore = ['SQL', 'Data Analytics', 'Power BI', 'Python'].includes(a.category) ? -1 : 1;
      const bScore = ['SQL', 'Data Analytics', 'Power BI', 'Python'].includes(b.category) ? -1 : 1;
      return aScore - bScore;
    });
  } else if (role === 'AI/ML Engineer') {
    pool.sort((a, b) => {
      const aScore = ['AI/ML', 'Generative AI', 'Python', 'Coding'].includes(a.category) ? -1 : 1;
      const bScore = ['AI/ML', 'Generative AI', 'Python', 'Coding'].includes(b.category) ? -1 : 1;
      return aScore - bScore;
    });
  } else if (role === 'Prompt Engineer') {
    pool.sort((a, b) => {
      const aScore = ['Prompt Engineering', 'Generative AI', 'AI/ML'].includes(a.category) ? -1 : 1;
      const bScore = ['Prompt Engineering', 'Generative AI', 'AI/ML'].includes(b.category) ? -1 : 1;
      return aScore - bScore;
    });
  } else if (role === 'Software Developer') {
    pool.sort((a, b) => {
      const aScore = ['Technical', 'Coding', 'SQL', 'Python'].includes(a.category) ? -1 : 1;
      const bScore = ['Technical', 'Coding', 'SQL', 'Python'].includes(b.category) ? -1 : 1;
      return aScore - bScore;
    });
  }

  // Prioritize matching difficulty while keeping full pool available for longer sessions
  const matchingDiff = pool.filter((q) => q.difficulty === difficulty);
  const otherDiff = pool.filter((q) => q.difficulty !== difficulty);
  const combined = [...matchingDiff, ...otherDiff];

  // If pool has fewer than requestedCount, return all available without truncation
  return combined.length >= requestedCount ? combined.slice(0, requestedCount) : combined;
}

// Helper to get an unused question from the bank
export function getNextUnusedBankQuestion(
  mode: string,
  role: string,
  difficulty: DifficultyLevel,
  alreadyAskedQuestions: string[]
): BankQuestion {
  const pool = getQuestionsForConfig(mode, role, difficulty, 200);
  const unasked = pool.filter(
    (q) => !alreadyAskedQuestions.some((asked) => asked.toLowerCase().trim() === q.question.toLowerCase().trim())
  );

  if (unasked.length > 0) {
    return unasked[0];
  }

  // If entire filtered pool was asked, pick any unasked from general question bank
  const generalUnasked = QUESTION_BANK.filter(
    (q) => !alreadyAskedQuestions.some((asked) => asked.toLowerCase().trim() === q.question.toLowerCase().trim())
  );

  if (generalUnasked.length > 0) {
    return generalUnasked[0];
  }

  // Fallback to pool item with cycle
  const idx = alreadyAskedQuestions.length % pool.length;
  return pool[idx] || QUESTION_BANK[0];
}
